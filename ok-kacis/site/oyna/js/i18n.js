  let current = 'en';
  let plural = null;
  const listeners = [];
  const byCode = (code) => LANGS.find((l) => l.code === code);

  /** Kayıtlı seçim varsa onu, yoksa cihaz dilini, o da yoksa İngilizceyi seçer. */
  function detect(saved) {
    if (saved && STRINGS[saved]) return saved;
    const nav = (root && root.navigator) || {};
    const prefs = (nav.languages && nav.languages.length ? nav.languages : [nav.language || '']).map((l) =>
      String(l || '').toLowerCase()
    );
    for (const l of prefs) {
      const base = l.split('-')[0];
      if (STRINGS[base]) return base;
    }
    return 'en';
  }

  function loadFont(lang) {
    if (!lang.font || !root || !root.document) return;
    // iOS/Android uygulamasında telefonun kendi Japonca/Korece yazı tipi kullanılır (internet gerekmez)
    const C = root.Capacitor;
    if (C && typeof C.isNativePlatform === 'function' && C.isNativePlatform()) return;
    const id = 'font-' + lang.code;
    if (root.document.getElementById(id)) return;
    const link = root.document.createElement('link');
    link.id = id;
    link.rel = 'stylesheet';
    link.href = 'https://fonts.googleapis.com/css2?family=' + lang.font + '&display=swap';
    root.document.head.appendChild(link);
  }

  function set(code) {
    current = STRINGS[code] ? code : 'en';
    const lang = byCode(current);
    try {
      plural = new Intl.PluralRules(lang.locale);
    } catch (e) {
      plural = null;
    }
    if (root && root.document) {
      root.document.documentElement.lang = current;
      loadFont(lang);
    }
    listeners.forEach((fn) => fn(current));
    return current;
  }

  function t(key, vars) {
    const table = STRINGS[current] || STRINGS.en;
    let s = null;
    if (vars && typeof vars.n === 'number' && plural && plural.select(vars.n) === 'one') {
      s = table[key + '_one'] != null ? table[key + '_one'] : null;
    }
    if (s == null) s = table[key] != null ? table[key] : STRINGS.en[key] != null ? STRINGS.en[key] : key;
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
    return s;
  }

  return {
    LANGS,
    STRINGS,
    t,
    set,
    detect,
    onChange(fn) {
      listeners.push(fn);
    },
    get lang() {
      return current;
    },
    get locale() {
      return byCode(current).locale;
    },
  };
